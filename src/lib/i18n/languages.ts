const BY_CODE: ReadonlyMap<string, LanguageEntry> = new Map(
  LANGUAGES.map((l) => [l.code, l])
);

/** Look up a language entry by ISO 639-1 code (case-insensitive). */
export function findLanguage(code: string | null | undefined): LanguageEntry | null {
  if (!code) return null;
  return BY_CODE.get(code.trim().toLowerCase()) ?? null;
}

/**
 * Resolve the English name we inject into LLM prompts. Falls back to
 * `'English'` for unknown / null codes — matches the historical behaviour
 * of the LANGUAGE_NAMES maps in dynamic-audit.ts and retry-job.ts.
 */
export function languageNameForPrompt(code: string | null | undefined): string {
  return findLanguage(code)?.promptName ?? 'English';
}
